public class Contato {
    String nome;
    String telefone;
    String endereco;

    public void setNome(String str){
        this.nome = str;
    }
    
    public void setTelefone(String str) {
        this.telefone = str;
    }
    
    public void setEndereco(String str){
        this.endereco = str;
    }
}